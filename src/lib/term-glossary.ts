export function resolveTermDefinition(term: string, generatedDefinition?: string): string | undefined {
  const normalizedTerm = typeof term === 'string' ? term.trim() : ''
  const builtIn = definitions.get(normalizedTerm)
  if (builtIn !== undefined) return builtIn
  return typeof generatedDefinition === 'string' && generatedDefinition.trim()
    ? generatedDefinition.trim()
    : undefined
}
